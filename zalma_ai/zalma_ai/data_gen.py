URGENT = ["Срочно, лаборатория простаивает.", "Аварийная ситуация, идут исследования!",
          "Критично, ждём сегодня."]
NORMAL = ["Планово, в удобное время.", "Не срочно, когда будет возможность.",
          "Можно на следующей неделе."]


def make_inventory_and_sales(months: int = 36, seed: int = 42):
    rng = np.random.default_rng(seed)
    idx = pd.date_range("2023-01-01", periods=months, freq="MS")
    rows = []
    for sku, _, base, trend, amp, _, _ in SKUS:
        for i, d in enumerate(idx):
            # пик в ноябре-декабре (бюджетный цикл), спад в январе-феврале
            season = amp * np.cos(2 * np.pi * (d.month - 12) / 12)
            mu = base * (1 + trend / 100) ** i * (1 + season)
            rows.append((sku, d.strftime("%Y-%m-%d"), max(0, int(rng.normal(mu, mu * 0.08)))))
    sales = pd.DataFrame(rows, columns=["sku", "month", "qty"])
    inv = pd.DataFrame([(s[0], s[1], s[5], s[6]) for s in SKUS],
                       columns=["sku", "name", "lead_months", "stock"])
    return sales, inv


def make_tickets(n: int = 400, seed: int = 7) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    rows = []
    for _ in range(n):
        t = rng.choice(list(TICKET_TEMPLATES))
        txt = rng.choice(TICKET_TEMPLATES[t]).format(eq=rng.choice(EQUIPMENT))
        urgent = rng.random() < (0.55 if t in ("гарантия", "ремонт") else 0.1)
        txt += " " + rng.choice(URGENT if urgent else NORMAL)
        rows.append((txt, t, "срочно" if urgent else "обычно"))
    return pd.DataFrame(rows, columns=["text", "type", "priority"])


def generate(path: Path = DATA) -> Path:
    path = Path(path)
    (path / "catalog").mkdir(parents=True, exist_ok=True)
    sales, inv = make_inventory_and_sales()
    sales.to_csv(path / "sales.csv", index=False)
    inv.to_csv(path / "inventory.csv", index=False)
    make_tickets().to_csv(path / "tickets.csv", index=False)
    for name, text in CATALOG.items():
        (path / "catalog" / name).write_text(text, encoding="utf-8")
    return path
